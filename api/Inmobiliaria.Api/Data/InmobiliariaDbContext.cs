using Inmobiliaria.Api.Entities;
using Microsoft.EntityFrameworkCore;
namespace Inmobiliaria.Api.Data;
public sealed class InmobiliariaDbContext(DbContextOptions<InmobiliariaDbContext> options) : DbContext(options)
{
    public DbSet<Roles> Roles => Set<Roles>();
    public DbSet<Usuarios> Usuarios => Set<Usuarios>();
    public DbSet<Compradores> Compradores => Set<Compradores>();
    public DbSet<Vendedores> Vendedores => Set<Vendedores>();
    public DbSet<Administradores> Administradores => Set<Administradores>();
    public DbSet<TiposPropiedad> TiposPropiedad => Set<TiposPropiedad>();
    public DbSet<Provincias> Provincias => Set<Provincias>();
    public DbSet<Caracteristicas> Caracteristicas => Set<Caracteristicas>();
    public DbSet<Propiedades> Propiedades => Set<Propiedades>();
    public DbSet<PropiedadCaracteristicas> PropiedadCaracteristicas => Set<PropiedadCaracteristicas>();
    public DbSet<Publicaciones> Publicaciones => Set<Publicaciones>();
    public DbSet<ImagenesPropiedades> ImagenesPropiedades => Set<ImagenesPropiedades>();
    public DbSet<Favoritos> Favoritos => Set<Favoritos>();
    public DbSet<BusquedasGuardadas> BusquedasGuardadas => Set<BusquedasGuardadas>();
    public DbSet<Solicitudes> Solicitudes => Set<Solicitudes>();
    public DbSet<Visitas> Visitas => Set<Visitas>();
    public DbSet<Reservaciones> Reservaciones => Set<Reservaciones>();
    public DbSet<Conversaciones> Conversaciones => Set<Conversaciones>();
    public DbSet<Mensajes> Mensajes => Set<Mensajes>();
    public DbSet<Reportes> Reportes => Set<Reportes>();
    public DbSet<HistorialAprobaciones> HistorialAprobaciones => Set<HistorialAprobaciones>();
    public DbSet<Notificaciones> Notificaciones => Set<Notificaciones>();
    public DbSet<Pagos> Pagos => Set<Pagos>();
    public DbSet<Contratos> Contratos => Set<Contratos>();
    public DbSet<Suspensiones> Suspensiones => Set<Suspensiones>();
    public DbSet<HistorialAcciones> HistorialAcciones => Set<HistorialAcciones>();
    protected override void OnModelCreating(ModelBuilder model)
    {
        model.Entity<Favoritos>().HasKey(x => new { x.IdComprador, x.IdPublicacion });
        model.Entity<PropiedadCaracteristicas>().HasKey(x => new { x.IdPropiedad, x.IdCaracteristica });
        model.Entity<Roles>().HasIndex(x => x.Nombre).IsUnique();
        model.Entity<Usuarios>().HasIndex(x => x.Correo).IsUnique();
        model.Entity<Compradores>().HasIndex(x => x.IdUsuario).IsUnique();
        model.Entity<Compradores>().HasIndex(x => x.Cedula).IsUnique();
        model.Entity<Vendedores>().HasIndex(x => x.IdUsuario).IsUnique();
        model.Entity<Vendedores>().HasIndex(x => x.Cedula).IsUnique();
        model.Entity<Administradores>().HasIndex(x => x.IdUsuario).IsUnique();
        model.Entity<TiposPropiedad>().HasIndex(x => x.Nombre).IsUnique();
        model.Entity<Provincias>().HasIndex(x => x.Nombre).IsUnique();
        model.Entity<Caracteristicas>().HasIndex(x => x.Nombre).IsUnique();
        model.Entity<Reservaciones>().HasIndex(x => x.IdSolicitud).IsUnique();
        model.Entity<Contratos>().HasIndex(x => x.NumeroContrato).IsUnique();
        model.Entity<Usuarios>().HasOne<Roles>().WithMany().HasForeignKey(x => x.IdRol).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Compradores>().HasOne<Usuarios>().WithMany().HasForeignKey(x => x.IdUsuario).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Vendedores>().HasOne<Usuarios>().WithMany().HasForeignKey(x => x.IdUsuario).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Vendedores>().HasOne<Usuarios>().WithMany().HasForeignKey(x => x.VerificadoPor).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Administradores>().HasOne<Usuarios>().WithMany().HasForeignKey(x => x.IdUsuario).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Propiedades>().HasOne<Vendedores>().WithMany().HasForeignKey(x => x.IdVendedor).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Propiedades>().HasOne<TiposPropiedad>().WithMany().HasForeignKey(x => x.IdTipoPropiedad).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Propiedades>().HasOne<Provincias>().WithMany().HasForeignKey(x => x.IdProvincia).OnDelete(DeleteBehavior.NoAction);
        model.Entity<PropiedadCaracteristicas>().HasOne<Propiedades>().WithMany().HasForeignKey(x => x.IdPropiedad).OnDelete(DeleteBehavior.NoAction);
        model.Entity<PropiedadCaracteristicas>().HasOne<Caracteristicas>().WithMany().HasForeignKey(x => x.IdCaracteristica).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Publicaciones>().HasOne<Propiedades>().WithMany().HasForeignKey(x => x.IdPropiedad).OnDelete(DeleteBehavior.NoAction);
        model.Entity<ImagenesPropiedades>().HasOne<Propiedades>().WithMany().HasForeignKey(x => x.IdPropiedad).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Favoritos>().HasOne<Compradores>().WithMany().HasForeignKey(x => x.IdComprador).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Favoritos>().HasOne<Publicaciones>().WithMany().HasForeignKey(x => x.IdPublicacion).OnDelete(DeleteBehavior.NoAction);
        model.Entity<BusquedasGuardadas>().HasOne<Compradores>().WithMany().HasForeignKey(x => x.IdComprador).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Solicitudes>().HasOne<Compradores>().WithMany().HasForeignKey(x => x.IdComprador).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Solicitudes>().HasOne<Publicaciones>().WithMany().HasForeignKey(x => x.IdPublicacion).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Visitas>().HasOne<Solicitudes>().WithMany().HasForeignKey(x => x.IdSolicitud).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Reservaciones>().HasOne<Solicitudes>().WithMany().HasForeignKey(x => x.IdSolicitud).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Conversaciones>().HasOne<Compradores>().WithMany().HasForeignKey(x => x.IdComprador).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Conversaciones>().HasOne<Vendedores>().WithMany().HasForeignKey(x => x.IdVendedor).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Conversaciones>().HasOne<Publicaciones>().WithMany().HasForeignKey(x => x.IdPublicacion).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Mensajes>().HasOne<Conversaciones>().WithMany().HasForeignKey(x => x.IdConversacion).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Mensajes>().HasOne<Usuarios>().WithMany().HasForeignKey(x => x.IdRemitente).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Reportes>().HasOne<Usuarios>().WithMany().HasForeignKey(x => x.IdUsuarioReporta).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Reportes>().HasOne<Publicaciones>().WithMany().HasForeignKey(x => x.IdPublicacion).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Reportes>().HasOne<Usuarios>().WithMany().HasForeignKey(x => x.IdUsuarioReportado).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Reportes>().HasOne<Usuarios>().WithMany().HasForeignKey(x => x.ResueltoPor).OnDelete(DeleteBehavior.NoAction);
        model.Entity<HistorialAprobaciones>().HasOne<Vendedores>().WithMany().HasForeignKey(x => x.IdVendedor).OnDelete(DeleteBehavior.NoAction);
        model.Entity<HistorialAprobaciones>().HasOne<Administradores>().WithMany().HasForeignKey(x => x.IdAdministrador).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Notificaciones>().HasOne<Usuarios>().WithMany().HasForeignKey(x => x.IdUsuarioDestino).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Pagos>().HasOne<Compradores>().WithMany().HasForeignKey(x => x.IdComprador).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Pagos>().HasOne<Solicitudes>().WithMany().HasForeignKey(x => x.IdSolicitud).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Pagos>().HasOne<Reservaciones>().WithMany().HasForeignKey(x => x.IdReservacion).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Contratos>().HasOne<Solicitudes>().WithMany().HasForeignKey(x => x.IdSolicitud).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Suspensiones>().HasOne<Usuarios>().WithMany().HasForeignKey(x => x.IdUsuario).OnDelete(DeleteBehavior.NoAction);
        model.Entity<Suspensiones>().HasOne<Administradores>().WithMany().HasForeignKey(x => x.IdAdministrador).OnDelete(DeleteBehavior.NoAction);
        model.Entity<HistorialAcciones>().HasOne<Usuarios>().WithMany().HasForeignKey(x => x.IdUsuario).OnDelete(DeleteBehavior.NoAction);
        model.Entity<ImagenesPropiedades>().HasIndex(x => x.IdPropiedad).IsUnique().HasFilter("[EsPrincipal] = 1");
    }
}
